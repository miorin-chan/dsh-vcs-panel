/**
 * Build this plugin's Host and Client artifacts from TypeScript sources.
 *
 *   src/host/index.ts       → index.js              ESM for the Host process
 *   src/client/index.tsx    → client.js             classic script for the Web module loader
 *   src/lib/<path>.ts       → lib/<path>.js         private Host runtime modules
 *   src/client/<path>.ts    → lib/client/<path>.js  Node-loadable mirror of the Client's pure modules
 *
 * DSH serves one classic script per plugin; its module loader runs the wrapper
 * factory lazily and provides `react` and the seeded platform modules from the
 * shell's frozen table. Everything else is inlined, so the Client artifact is
 * self-contained apart from those externals.
 *
 * The build emits the private Host modules under `lib/` so `index.js` and
 * `test/` can import them directly.
 * The same reason applies to the Client's pure modules: `test/` imports their
 * behavior directly, and the bundled `client.js` cannot expose module internals,
 * so each one is emitted as an ES module under `lib/client/`.
 *
 * Stylesheets are inlined as text through esbuild's `text` loader, which is why
 * the Client build sets that loader and the source declares the module type.
 *
 * Usage:
 *   node scripts/build.mjs           write every artifact
 *   node scripts/build.mjs --check   fail when an artifact is stale
 *
 * The `prepare` script builds the local artifacts during dependency installation
 * and packaging. Use `--check` to compare existing artifacts with the sources.
 */

import { createRequire } from 'node:module'
import { existsSync } from 'node:fs'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const { build } = require('esbuild')

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const pkg = JSON.parse(await readFile(resolve(ROOT, 'package.json'), 'utf8'))

/** Packages the Web shell seeds into its module table; every other import is bundled. */
const CLIENT_EXTERNAL = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/*',
]

const HOST_EXTERNAL = ['node:*']

/** Source and output directories for private Host modules. */
const MODULES = { source: 'src/lib', output: 'lib' }

/** Client source and output directories for the Node-loadable test mirror. */
const CLIENT_MODULES = { source: 'src/client', output: 'lib/client' }

/** Rewrite `../lib/<name>.js` from `src/host` to `./lib/<name>.js` in the generated `index.js`. */
const HOST_MODULE_IMPORT = /^\.\.\/lib\/(.+\.js)$/

/** Keep `src/host`'s private-module imports pointing at the generated `lib/` artifacts. */
const hostModules = {
  name: 'host-modules',
  setup(context) {
    context.onResolve({ filter: HOST_MODULE_IMPORT }, (args) => ({
      path: './' + MODULES.output + '/' + HOST_MODULE_IMPORT.exec(args.path)[1],
      external: true,
    }))
  },
}

/** Wrap an esbuild CommonJS bundle in DSH's module-loader envelope. */
function envelope(code) {
  return `/**
 * ${pkg.name} browser half. Generated by scripts/build.mjs from src/client/;
 * do not edit by hand. React and the seeded platform modules come from the
 * host module table.
 */
window.__ModuleLoader__.load({
  id: '${pkg.name}',
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  },
});
`
}

/** The first existing entry among `candidates`, resolved from the package root. */
function entryOf(candidates) {
  return candidates.map((name) => resolve(ROOT, name)).find((path) => existsSync(path))
}

/** Every `.ts` source under `dir`, as `/`-joined paths relative to it, sorted. */
async function sourcesOf(dir) {
  const found = []
  async function walk(prefix) {
    const entries = await readdir(resolve(dir, prefix), { withFileTypes: true })
    for (const entry of entries) {
      const path = prefix === '' ? entry.name : `${prefix}/${entry.name}`
      if (entry.isDirectory()) {
        await walk(path)
      } else if (entry.name.endsWith('.ts') && !entry.name.endsWith('.d.ts')) {
        found.push(path)
      }
    }
  }
  await walk('')
  return found.sort()
}

async function compile(entry, options, banner) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    banner: { js: banner },
    jsx: 'automatic',
    minify: false,
    legalComments: 'none',
    logLevel: 'warning',
    ...options,
  })
  return result.outputFiles[0].text
}

/**
 * Compile one module on its own, leaving every import specifier untouched.
 * A private module keeps its `./sibling.js` imports because the emitted tree
 * mirrors the source tree, and the artifact runs from `lib/`.
 */
async function compileModule(entry, options, banner) {
  const result = await build({
    entryPoints: [entry],
    bundle: false,
    write: false,
    banner: { js: banner },
    legalComments: 'none',
    logLevel: 'warning',
    ...options,
  })
  return result.outputFiles[0].text
}

const targets = []

const hostEntry = entryOf(['src/host/index.ts'])
if (hostEntry !== undefined) {
  const banner = `/** ${pkg.name} host half. Generated by scripts/build.mjs from src/host/; do not edit by hand. */`
  const code = await compile(hostEntry, {
    format: 'esm',
    platform: 'node',
    external: HOST_EXTERNAL,
    plugins: [hostModules],
  }, banner)
  targets.push({ file: 'index.js', content: code })
}

const clientEntry = entryOf(['src/client/index.tsx', 'src/client/index.ts'])
if (clientEntry !== undefined) {
  const code = await compile(clientEntry, {
    format: 'cjs',
    platform: 'browser',
    target: 'es2020',
    external: CLIENT_EXTERNAL,
    loader: { '.css': 'text' },
    minify: true,
  }, '')
  targets.push({ file: 'client.js', content: envelope(code) })
}

const moduleDir = resolve(ROOT, MODULES.source)
if (existsSync(moduleDir)) {
  for (const path of await sourcesOf(moduleDir)) {
    const banner = `/** ${pkg.name} host runtime module. Generated by scripts/build.mjs from ${MODULES.source}/; do not edit by hand. */`
    const code = await compileModule(resolve(moduleDir, path), {
      format: 'esm',
      platform: 'node',
      target: 'es2022',
    }, banner)
    targets.push({ file: `${MODULES.output}/${path.replace(/\.ts$/, '.js')}`, content: code })
  }
}

const clientModuleDir = resolve(ROOT, CLIENT_MODULES.source)
if (existsSync(clientModuleDir)) {
  for (const path of await sourcesOf(clientModuleDir)) {
    const banner = `/** ${pkg.name} Client module for Node tests. Generated by scripts/build.mjs from ${CLIENT_MODULES.source}/; do not edit by hand. */`
    const code = await compileModule(resolve(clientModuleDir, path), {
      format: 'esm',
      platform: 'neutral',
      target: 'es2020',
    }, banner)
    targets.push({ file: `${CLIENT_MODULES.output}/${path.replace(/\.ts$/, '.js')}`, content: code })
  }
}

if (targets.length === 0) {
  console.error('no Host or Client entry under src/; nothing to build')
  process.exitCode = 1
}

let stale = false
for (const { file, content } of targets ?? []) {
  const output = resolve(ROOT, file)
  if (CHECK) {
    const current = existsSync(output) ? await readFile(output, 'utf8') : ''
    if (current !== content) {
      console.error(`${file} is stale; run \`node scripts/build.mjs\`.`)
      stale = true
    } else {
      console.log(`${file} is up to date.`)
    }
  } else {
    await mkdir(dirname(output), { recursive: true })
    await writeFile(output, content)
    console.log(`wrote ${file} (${(content.length / 1024).toFixed(1)} KiB)`)
  }
}
if (stale) process.exitCode = 1
